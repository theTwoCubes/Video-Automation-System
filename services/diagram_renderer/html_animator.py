"""
HTML/CSS Animated Diagram Renderer.

Instead of Manim (requires LaTeX, Cairo, very heavy on Windows), this renderer:
1. Takes an HTML+CSS animation string generated by the LLM
2. Uses Playwright to capture frames at 100ms intervals for N seconds
3. Uses FFmpeg to assemble frames into a smooth animated diagram video

The LLM generates self-contained HTML with CSS @keyframe animations for:
- Memory layout diagrams (stack/heap visualization)
- Compilation pipeline flows
- Pointer/reference illustrations
- Call stack animations
- Loop/iteration step-throughs
"""
import subprocess
from pathlib import Path
from typing import Optional


def _fwd(p: Path) -> str:
    return str(p.resolve()).replace("\\", "/")


def capture_animation_frames(
    html_content: str,
    frames_dir: Path,
    capture_fps: int = 10,
    duration_sec: float = 4.0,
    width: int = 1920,
    height: int = 1080,
) -> list[str]:
    """
    Load an HTML animation in Playwright and capture frames at capture_fps.
    Returns list of PNG frame paths.
    """
    import asyncio
    from playwright.async_api import async_playwright

    frames_dir.mkdir(parents=True, exist_ok=True)
    frame_paths = []
    interval_ms = int(1000 / capture_fps)
    total_frames = int(duration_sec * capture_fps)

    async def _capture():
        async with async_playwright() as p:
            browser = await p.chromium.launch()
            page = await browser.new_page(
                viewport={"width": width, "height": height}
            )
            await page.set_content(html_content, wait_until="domcontentloaded")

            # let CSS animations start
            await page.wait_for_timeout(100)

            for frame_num in range(total_frames):
                out = str(frames_dir / f"frame_{frame_num:04d}.png")
                await page.screenshot(path=out, type="png", full_page=False)
                frame_paths.append(out)
                if frame_num < total_frames - 1:
                    await page.wait_for_timeout(interval_ms)

            await browser.close()

    try:
        asyncio.run(_capture())
    except RuntimeError:
        import nest_asyncio
        nest_asyncio.apply()
        import asyncio
        asyncio.get_event_loop().run_until_complete(_capture())

    return frame_paths


def assemble_diagram_video(
    frame_paths: list[str],
    output_path: str,
    ffmpeg_exe: str,
    capture_fps: int = 10,
) -> Optional[str]:
    """Assemble PNG frames into an MP4 using FFmpeg. No audio."""
    if not frame_paths:
        return None

    # write frame list
    concat_file = Path(output_path).parent / f"diag_frames_{Path(output_path).stem}.txt"
    with open(concat_file, "w", encoding="utf-8") as f:
        for fp in frame_paths:
            f.write(f"file '{_fwd(Path(fp))}'\n")
            f.write(f"duration {1.0 / capture_fps:.4f}\n")
        f.write(f"file '{_fwd(Path(frame_paths[-1]))}'\n")

    cmd = [
        ffmpeg_exe, "-y",
        "-f", "concat", "-safe", "0", "-i", _fwd(concat_file),
        "-vf", "scale=1920:1080:flags=lanczos,fps=30",
        "-an",
        "-c:v", "libx264", "-pix_fmt", "yuv420p", "-preset", "fast", "-crf", "22",
        _fwd(Path(output_path)),
    ]
    result = subprocess.run(cmd, capture_output=True, text=True)
    concat_file.unlink(missing_ok=True)

    if result.returncode == 0 and Path(output_path).exists():
        return output_path
    else:
        print(f"  Diagram video assembly failed: {result.stderr[-150:]}")
        return None


def render_animated_diagram(
    html_content: str,
    output_path: str,
    ffmpeg_exe: str,
    duration_sec: float = 4.0,
    capture_fps: int = 10,
) -> Optional[str]:
    """
    Full pipeline: HTML animation → Playwright frames → FFmpeg MP4.
    Returns path to the video file or None on failure.
    """
    output_abs = Path(output_path).resolve()
    frames_dir = output_abs.parent / f"diag_frames_{output_abs.stem}"

    try:
        print(f"  Capturing {int(duration_sec * capture_fps)} animation frames...")
        frames = capture_animation_frames(
            html_content, frames_dir,
            capture_fps=capture_fps,
            duration_sec=duration_sec,
        )
        if not frames:
            return None

        return assemble_diagram_video(frames, str(output_abs), ffmpeg_exe, capture_fps)
    except Exception as e:
        print(f"  Animated diagram render failed: {e}")
        return None
