import copy
from agents.base_agent import BaseAgent

SYSTEM_PROMPT = """
You are a phonetic translation expert for a TTS (Text-to-Speech) pipeline.
Your job is to take a video script and rewrite it phonetically so the AI voice generator pronounces everything correctly. This is NOT just for programming languages—it applies to math equations, complex symbols, domain-specific acronyms, or any non-standard text.

RULES:
1. Preserve the exact tone, pacing, and length of the original text.
2. Translate ALL syntax, symbols, equations, and acronyms into spoken English words according to the context.
   - Example (Math): `E = mc^2` -> "E equals m c squared"
   - Example (C++): `std::cout << "Hello";` -> "standard c out left shift Hello"
   - Example (JS): `() => {}` -> "empty arrow function"
   - Example (Symbols): `100 & 200` -> "one hundred bitwise and two hundred"
3. Do NOT add new information or conversational filler.
4. If a segment does not contain any code or symbols that would be mispronounced, just copy the text exactly as is.

INPUT FORMAT:
You will receive a JSON structure containing a "segments" array.

OUTPUT FORMAT:
You MUST output the identical JSON structure you received, but for each segment, add a new string field called "spoken_text" containing your phonetically translated version. Keep the original "text" field unchanged.

Example Output:
{
  "segments": [
    {
      "type": "narration",
      "text": "The formula is a^2 + b^2 = c^2.",
      "spoken_text": "The formula is a squared plus b squared equals c squared."
    }
  ]
}

Output strictly valid JSON. No markdown wrappers.
"""

USER_TEMPLATE = """
Here is the script to process:
{script_json}
"""

class PhoneticAgent(BaseAgent):
    """
    Takes the script generated by the ScriptAgent and adds a 'spoken_text'
    field to each segment, spelling out code and symbols phonetically for the TTS engine.
    """
    
    def run(self, state: dict) -> dict:
        print("[PhoneticAgent] Generating phonetic translations for TTS...")
        
        script = state.get("script", {})
        if not script or "segments" not in script:
            print("  No script segments found. Skipping.")
            return state

        import json
        script_json = json.dumps(script, indent=2)
        
        user_msg = USER_TEMPLATE.format(script_json=script_json)
        
        try:
            # Parse the JSON response
            phonetic_script = self.llm.complete_json(SYSTEM_PROMPT, user_msg)
            
            # Safely merge the spoken_text back into the state to avoid losing other fields
            orig_segments = script.get("segments", [])
            phon_segments = phonetic_script.get("segments", [])
            
            if len(orig_segments) != len(phon_segments):
                print(f"  [PhoneticAgent] Warning: Length mismatch ({len(orig_segments)} vs {len(phon_segments)}). Using original script.")
                return state

            new_segments = []
            for orig_seg, new_seg in zip(orig_segments, phon_segments):
                merged_seg = copy.deepcopy(orig_seg)
                merged_seg["spoken_text"] = new_seg.get("spoken_text", orig_seg.get("text", ""))
                new_segments.append(merged_seg)
                
            state["script"]["segments"] = new_segments
            
            print(f"  Phonetic translation complete for {len(new_segments)} segments.")
            
        except Exception as e:
            print(f"  [PhoneticAgent] Error generating phonetic script: {e}")
            state["error"] = str(e)
            
        return state
